def _generate_headline_samples(gen, n: int, seed: int):
    """Generate ``n`` headline windows in [-1, 1] space from the frozen circuit.

    Copied VERBATIM from run_baselines.generate_wgan_samples (the canonical
    *0.1 sample space the shared reconstruct_od inverse consumes; RESEARCH
    Pitfall 6 — Apple MPS has no float64 statevector path so the quantum
    generator stays on CPU). FIXED ``np.random.default_rng(seed)`` — no global
    ``np.random.seed``. The seed is the recorded ``generation_seed`` (D-14-05).
    """
    import numpy as np
    import torch

    from revision.core import BATCH_SIZE, NOISE_HIGH, NOISE_LOW, NUM_QUBITS

    gen = gen.to("cpu")
    rng = np.random.default_rng(seed)
    out_parts: list = []
    remaining = n
    with torch.no_grad():
        while remaining > 0:
            bs = min(BATCH_SIZE, remaining)
            noise = torch.tensor(
                rng.uniform(NOISE_LOW, NOISE_HIGH, size=(NUM_QUBITS, bs)),
                dtype=torch.float32,
            )
            out = gen(noise).to(torch.float64) * 0.1
            out_parts.append(out.cpu().numpy())
            remaining -= bs
    return np.concatenate(out_parts, axis=0)[:n]


def _reconstruct_od_from_samples(samples_pm1, mu: float, sigma: float,
                                 r_min: float, r_max: float,
                                 od_starts_pool, seed: int):
    """Pipeline-B [-1,1] -> OD reconstruction, VERBATIM from
    run_dualscale_fidelity.reconstruct_od (Pipeline-B branch).

    The ``np.random.default_rng(seed*7919+1)`` od_start draw is load-bearing —
    do NOT change it (matches the frozen baseline reconstruction recipe so the
    headline reconciles with fidelity_dualscale.json). mu/sigma are the
    checkpoint's STORED scalars (D-14-05).
    """
    import numpy as np
    import torch

    from revision.core.preprocessing import inverse_logreturns

    samples_pm1 = np.asarray(samples_pm1, dtype=np.float64)
    r_norm = ((samples_pm1 + 1.0) / 2.0) * (r_max - r_min) + r_min
    rng = np.random.default_rng(seed * 7919 + 1)
    od_start_per_window = rng.choice(
        od_starts_pool, size=r_norm.shape[0], replace=True
    )
    r_norm_t = torch.tensor(r_norm)
    od_start_t = torch.tensor(od_start_per_window)
    od_full = inverse_logreturns(
        r_norm_t, od_start_t, torch.tensor(mu), torch.tensor(sigma)
    )
    od = od_full.cpu().numpy()
    if od.shape[1] == 11:
        od = od[:, :10]
    return od, r_norm


def _od_scale_rows(od, real_OD_flat, real_windowed_OD) -> list:
    """Every eval.py metric on the OD scale (D-11-10 — NO new metric math).

    Structure copied from run_dualscale_fidelity._od_scale_rows (same metric
    suite + DTW sub-sample recipe). Every row carries ``scale="OD"``.
    """
    import numpy as np

    from revision.core.eval import (
        compute_acf,
        compute_dtw,
        compute_emd,
        compute_moments,
    )

    mk, p = "quantum", "B"
    out = []
    synth_flat = od.reshape(-1)
    out.append(dict(model_kind=mk, pipeline=p, metric_name="emd",
                    scale="OD", value=compute_emd(real_OD_flat, synth_flat)))
    for k, v in compute_moments(synth_flat).items():
        out.append(dict(model_kind=mk, pipeline=p,
                        metric_name=f"moment_{k}", scale="OD", value=v))
    acfs = np.stack([compute_acf(w, nlags=NLAGS) for w in od])
    for lag in range(NLAGS + 1):
        out.append(dict(model_kind=mk, pipeline=p,
                        metric_name=f"acf_lag{lag}_mean", scale="OD",
                        value=float(acfs[:, lag].mean())))
        out.append(dict(model_kind=mk, pipeline=p,
                        metric_name=f"acf_lag{lag}_std", scale="OD",
                        value=float(acfs[:, lag].std())))
    rng = np.random.default_rng(42 * 31)
    synth_idx = rng.choice(od.shape[0],
                           size=min(DTW_N_PAIRS, od.shape[0]), replace=False)
    real_idx = rng.choice(real_windowed_OD.shape[0],
                          size=min(64, real_windowed_OD.shape[0]),
                          replace=False)
    dtw_vals = []
    for i in synth_idx:
        best = min(compute_dtw(od[i], real_windowed_OD[j]) for j in real_idx)
        dtw_vals.append(best)
    out.append(dict(model_kind=mk, pipeline=p, metric_name="dtw_mean",
                    scale="OD", value=float(np.mean(dtw_vals))))
    out.append(dict(model_kind=mk, pipeline=p, metric_name="dtw_median",
                    scale="OD", value=float(np.median(dtw_vals))))
    out.append(dict(model_kind=mk, pipeline=p, metric_name="dtw_std",
                    scale="OD", value=float(np.std(dtw_vals))))
    return out


