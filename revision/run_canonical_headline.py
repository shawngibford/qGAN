def _resolve_checkpoint() -> Path:
    """Locate ``best_checkpoint.pt`` (D-14-02 ground truth).

    .gitignored, so in a Claude Code worktree it is NOT copied in — it lives
    in the main checkout. Resolve via, in order: REPO root, cwd, then the
    main-repo toplevel that this worktree's ``.git`` file points at. Copied
    verbatim from run_recover_canonical.py:101-133 (T-14-14 — same ground
    truth tensor as Plan 01).
    """
    candidates = [REPO / "best_checkpoint.pt", Path.cwd() / "best_checkpoint.pt"]

    git_link = REPO / ".git"
    if git_link.is_file():
        try:
            gitdir = git_link.read_text().strip()
            if gitdir.startswith("gitdir:"):
                wt_git = Path(gitdir.split(":", 1)[1].strip())
                for anc in wt_git.parents:
                    if anc.name == ".git":
                        main_root = anc.parent
                        candidates.append(main_root / "best_checkpoint.pt")
                        break
        except OSError:
            pass

    for c in candidates:
        if c.exists():
            return c.resolve()
    raise RuntimeError(
        "best_checkpoint.pt not found (D-14-02 ground truth missing); "
        f"looked in: {[str(c) for c in candidates]}"
    )


def _sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _scalar(v) -> float:
    """Read a stored 0-dim tensor / python scalar VERBATIM (D-14-05)."""
    try:
        return float(v.item())
    except AttributeError:
        return float(v)


